package vterm

import "unicode"

// runeWidth returns the number of columns a rune occupies as xterm.js with
// the Unicode 11 provider lays it out: 0 for combining marks and other
// zero-width code points, 2 for East Asian Wide and Fullwidth characters,
// 1 for everything else.
func runeWidth(r rune) int {
	switch {
	case r == 0:
		return 0
	case r < 0x20 || (r >= 0x7f && r < 0xa0):
		return 0
	case r < 0x300:
		return 1
	}
	if isZeroWidth(r) {
		return 0
	}
	if isWide(r) {
		return 2
	}
	return 1
}

func isZeroWidth(r rune) bool {
	if unicode.Is(unicode.Mn, r) || unicode.Is(unicode.Me, r) || unicode.Is(unicode.Cf, r) {
		return true
	}
	switch {
	case r >= 0x1160 && r <= 0x11ff: // Hangul Jamo medial vowels and final consonants
		return true
	case r >= 0xd7b0 && r <= 0xd7ff:
		return true
	case r == 0x200b:
		return true
	}
	return false
}

